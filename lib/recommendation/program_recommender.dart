/// One recommended session: its workout, what it is for, and why.
class RecommendedWorkout {
  const RecommendedWorkout({
    required this.workout,
    required this.muscles,
    required this.exercises,
    required this.tags,
  });

  /// Ready to drop into a program.
  final Workout workout;

  /// The muscles this session is built around.
  final List<MuscleGroup> muscles;

  final List<RecommendedExercise> exercises;
  final List<RecommendationTag> tags;
}

/// A whole recommended program, with the reasoning attached.
class RecommendedProgram {
  const RecommendedProgram({
    required this.program,
    required this.workouts,
    required this.tags,
    required this.priorityMuscles,
    required this.usedProportions,
    this.note,
    this.scanTipExercises = const [],
    this.scanChangedPicks = 0,
  });

  /// A normal TrainingProgram, ready to save through the existing
  /// repository. Nothing about it is special once it is saved.
  final TrainingProgram program;

  final List<RecommendedWorkout> workouts;
  final List<RecommendationTag> tags;

  /// The muscles that were given priority, if any.
  final List<MuscleGroup> priorityMuscles;

  /// True when a body scan AND thresholds were both available, so
  /// proportion rules could actually change anything. False is the normal
  /// case today: see proportion_rules.dart.
  final bool usedProportions;

  /// Set when the result is thinner than asked for, so a screen can explain.
  final String? note;

  /// What the scan actually changed, so nothing claims more than happened.
  /// Exercises in this program that got a proportion setup tip, by name.
  final List<String> scanTipExercises;

  /// How many exercises in this program are different from the program the
  /// same profile and setup give without the scan (a proportion rule moved
  /// another variation ahead).
  final int scanChangedPicks;

  /// True when the scan changed anything at all: a tip or a different pick.
  bool get scanChangedProgram =>
      scanTipExercises.isNotEmpty || scanChangedPicks > 0;

  bool get isEmpty => workouts.every((w) => w.exercises.isEmpty);
}

/// Builds a whole program from what the app already knows.
///
/// Deterministic: the same profile, setup and scan always produce the same
/// program, in the same order, with the same tags. Nothing is random and
/// nothing is generated by a model.
///
/// It reads the exercise catalogue through ExerciseLibrary, so it works with
/// whatever is loaded, including the user's own exercises. No exercise is
/// named anywhere in this file.
class ProgramRecommender {
  const ProgramRecommender({
    this.engine,
    this.thresholds = ProportionThresholds.none,
  });

  final RecommendationEngine? engine;
  final ProportionThresholds thresholds;

  RecommendationEngine get activeEngine =>
      engine ?? RecommendationEngine(thresholds: thresholds);

  RecommendedProgram recommend({
    required UserProfile profile,
    required ProgramSetup setup,
    Measurement? measurement,
    DateTime? now,
  }) {
    final created = now ?? DateTime.now();
    final days = profile.trainingFrequency.days;
    final priority = priorityMusclesFor(setup);
    final split = splitFor(days: days, focus: setup.focus);

    // One session per workout in the split, each with its own muscles.
    final sessions = <RecommendedWorkout>[];
    for (final slot in splitSessions(split, setup)) {
      final result = activeEngine.recommendWorkout(
        profile: profile,
        setup: setup,
        measurement: measurement,
        priorityMuscles: priority,
        sessionMuscles: slot.muscles,
      );
      final workout = result.toWorkout(name: slot.name, focus: slot.focus);
      sessions.add(
        RecommendedWorkout(
          workout: workout,
          muscles: slot.muscles,
          exercises: result.exercises,
          tags: workoutTags(
            name: slot.name,
            sessionMuscles: slot.muscles,
            priorityMuscles: priority,
            sessionDuration: setup.sessionDuration,
          ),
        ),
      );
    }

    final workouts = [for (final s in sessions) s.workout];
    final program = TrainingProgram(
      id: generateId(),
      name: programNameFor(split, days),
      goal: setup.goal,
      setup: setup,
      workouts: workouts,
      schedule: scheduleFor(workouts, days),
      createdAt: created,
      updatedAt: created,
    );

    final thin = sessions.where((s) => s.exercises.isEmpty).length;
    final usedProportions = !thresholds.isEmpty && measurement != null;

    // What the scan changed: the tips it added, and the exercises that
    // differ from the same program built without it. Deterministic, so the
    // comparison is exact.
    final tips = <String>[];
    var changedPicks = 0;
    if (usedProportions) {
      for (final s in sessions) {
        for (final e in s.exercises) {
          if (e.setupCue != null && !tips.contains(e.exercise.name)) {
            tips.add(e.exercise.name);
          }
        }
      }
      final withoutScan = recommend(
        profile: profile,
        setup: setup,
        now: created,
      );
      final baseIds = {
        for (final s in withoutScan.workouts)
          for (final e in s.exercises) e.exercise.id,
      };
      final scanIds = {
        for (final s in sessions)
          for (final e in s.exercises) e.exercise.id,
      };
      changedPicks = scanIds.difference(baseIds).length;
    }
    final changed = tips.isNotEmpty || changedPicks > 0;

    return RecommendedProgram(
      scanTipExercises: tips,
      scanChangedPicks: changedPicks,
      // Saved with the program, so its page can say later whether it was
      // built from a scan, and whether the scan changed it.
      program: program.withScanBasis(
        used: usedProportions,
        takenAt: measurement?.takenAt,
        changed: changed,
      ),
      workouts: sessions,
      priorityMuscles: priority,
      usedProportions: usedProportions,
      tags: programTags(
        goal: setup.goal,
        focus: setup.focus,
        daysPerWeek: days,
        priorityMuscles: priority,
        sessionDuration: setup.sessionDuration,
      ),
      note: _joinNotes([
        if (thin > 0)
          '$thin of ${sessions.length} sessions came out empty. More '
              'equipment or more muscles would give more options.',
        limitationProgramNote(profile.limitations),
      ]),
    );
  }
}

String? _joinNotes(List<String?> notes) {
  final parts = [for (final n in notes) ?n];
  return parts.isEmpty ? null : parts.join('\n\n');
}

/// The muscles the user singled out, if they narrowed their focus.
///
/// There is no separate "priority" question, and none is added: choosing
/// fewer muscles than the focus covers IS the user saying those matter more.
/// Picking a focus and leaving it whole means no particular priority.
List<MuscleGroup> priorityMusclesFor(ProgramSetup setup) {
  final covered = musclesForFocus(setup.focus);
  final chosen = setup.muscles;
  if (chosen.isEmpty || chosen.length >= covered.length) return const [];
  return chosen;
}

/// Which split suits this many days a week.
///
///   2-3 days  full body     ACSM 2009: beginners train the entire body
///                           2-3 days a week (A); 3 days total-body for
///                           intermediates (B).
///   4 days    upper/lower   ACSM 2009: 4 days if using a split routine,
///                           upper/lower for intermediates (B).
///   5 days    upper/lower   Each half twice or three times a week. ACSM
///                           2009: a split routine trains each major muscle
///                           group twice a week (B).
///   6 days    push/pull/legs  Each session twice a week. ACSM 2009 says
///                           advanced lifters may use muscle-group splits at
///                           4-6 days (C); push/pull/legs is an APP CHOICE.
/// A narrowed focus overrides it, because a lower-body program has no
/// business being a push/pull split.
ProgramTemplate splitFor({required int days, required TrainingFocus focus}) {
  switch (focus) {
    case TrainingFocus.push:
    case TrainingFocus.pull:
    case TrainingFocus.upperBody:
    case TrainingFocus.lowerBody:
      // One kind of session, repeated across the week.
      return ProgramTemplate.fullBody;
    case TrainingFocus.fullBody:
    case TrainingFocus.chooseMuscles:
      if (days <= 3) return ProgramTemplate.fullBody;
      // 5 days stays upper/lower: push/pull/legs over 5 days would train
      // legs once a week, below ACSM's twice (B). Upper/lower gives 3 + 2.
      if (days <= 5) return ProgramTemplate.upperLower;
      return ProgramTemplate.pushPullLegs;
  }
}

/// One session in a split: its name and the muscles it is built around.
class SplitSession {
  const SplitSession({
    required this.name,
    required this.focus,
    required this.muscles,
  });

  final String name;
  final String focus;
  final List<MuscleGroup> muscles;
}

/// Core and lower back belong to neither upper nor lower body. Without a
/// home they were silently dropped from split programs; they go with the
/// lower-body day (APP CHOICE: the day that already trains the hips).
final List<MuscleGroup> _core = MuscleGroup.values
    .where((m) => m.region == MuscleRegion.core)
    .toList();

/// The sessions a split contains, narrowed to what the user actually chose.
///
/// A session whose muscles the user did not select is dropped rather than
/// filled with work they did not ask for.
List<SplitSession> splitSessions(ProgramTemplate split, ProgramSetup setup) {
  final chosen = setup.muscles.toSet();

  List<MuscleGroup> only(List<MuscleGroup> muscles) =>
      muscles.where(chosen.contains).toList();

  final sessions = <SplitSession>[];
  switch (split) {
    case ProgramTemplate.pushPullLegs:
      sessions.addAll([
        SplitSession(
          name: 'Push',
          focus: 'Push',
          muscles: only(
            musclesForFocus(
              TrainingFocus.push,
            ).where((m) => m.region != MuscleRegion.lower).toList(),
          ),
        ),
        SplitSession(
          name: 'Pull',
          focus: 'Pull',
          muscles: only(
            musclesForFocus(
              TrainingFocus.pull,
            ).where((m) => m.region != MuscleRegion.lower).toList(),
          ),
        ),
        SplitSession(
          name: 'Legs',
          focus: 'Lower body',
          muscles: only([...musclesForFocus(TrainingFocus.lowerBody), ..._core]),
        ),
      ]);
    case ProgramTemplate.upperLower:
      sessions.addAll([
        SplitSession(
          name: 'Upper',
          focus: 'Upper body',
          muscles: only(musclesForFocus(TrainingFocus.upperBody)),
        ),
        SplitSession(
          name: 'Lower',
          focus: 'Lower body',
          muscles: only([...musclesForFocus(TrainingFocus.lowerBody), ..._core]),
        ),
      ]);
    case ProgramTemplate.fullBody:
    case ProgramTemplate.custom:
      sessions.add(
        SplitSession(
          name: 'Full Body',
          focus: setup.focus == TrainingFocus.fullBody ? '' : setup.focus.label,
          muscles: setup.muscles,
        ),
      );
  }
  return sessions.where((s) => s.muscles.isNotEmpty).toList();
}

/// Deals the workouts onto training days, Monday first, spreading them out.
///
/// IMPLEMENTATION HEURISTIC: the days chosen and the rest between them are
/// conventions, not findings.
List<ScheduledWorkout> scheduleFor(List<Workout> workouts, int days) {
  if (workouts.isEmpty || days <= 0) return const [];
  final chosen = _trainingDays(days);
  return [
    for (var i = 0; i < chosen.length; i++)
      ScheduledWorkout(
        day: chosen[i],
        workoutId: workouts[i % workouts.length].id,
      ),
  ];
}

/// Which weekdays to train on, for a given number of days.
List<Weekday> _trainingDays(int days) {
  const byCount = <int, List<Weekday>>{
    1: [Weekday.monday],
    2: [Weekday.monday, Weekday.thursday],
    3: [Weekday.monday, Weekday.wednesday, Weekday.friday],
    4: [Weekday.monday, Weekday.tuesday, Weekday.thursday, Weekday.friday],
    5: [
      Weekday.monday,
      Weekday.tuesday,
      Weekday.wednesday,
      Weekday.friday,
      Weekday.saturday,
    ],
    6: [
      Weekday.monday,
      Weekday.tuesday,
      Weekday.wednesday,
      Weekday.thursday,
      Weekday.friday,
      Weekday.saturday,
    ],
  };
  return byCount[days] ?? byCount[3]!;
}

/// "4-Day Upper Lower", "3-Day Full Body".
String programNameFor(ProgramTemplate split, int days) =>
    '$days-Day ${split.label}';
