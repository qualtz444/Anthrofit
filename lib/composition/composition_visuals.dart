import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:path_provider/path_provider.dart';

import 'mask_codec.dart';
import 'silhouette_features.dart';

/// The outlines and photos from one body composition scan.
///
/// PRIVACY: these stay on this phone. They are files in the app's own
/// storage, never part of the profile, so they are never synced to Firebase.
/// Deleting the scan deletes them.
class CompositionVisuals {
  const CompositionVisuals({
    this.frontOutline,
    this.sideOutline,
    this.frontPhoto,
    this.sidePhoto,
  });

  final SilhouetteMask? frontOutline;
  final SilhouetteMask? sideOutline;

  /// JPEG bytes.
  final Uint8List? frontPhoto;
  final Uint8List? sidePhoto;

  bool get hasOutlines => frontOutline != null || sideOutline != null;
  bool get hasPhotos => frontPhoto != null || sidePhoto != null;
  bool get isEmpty => !hasOutlines && !hasPhotos;

  static const CompositionVisuals none = CompositionVisuals();
}

/// Saves and loads [CompositionVisuals], one folder per scan record id:
///
/// ```text
/// (app documents)/composition_visuals/(record id)/
///     front_outline.json   side_outline.json   (run-encoded masks)
///     front_original.jpg   side_original.jpg
/// ```
class CompositionVisualStore {
  CompositionVisualStore({Future<Directory> Function()? baseDirectory})
    : _baseDirectory = baseDirectory ?? getApplicationDocumentsDirectory;

  final Future<Directory> Function() _baseDirectory;

  static const String folder = 'composition_visuals';

  Future<Directory> _dirFor(String recordId) async {
    final base = await _baseDirectory();
    // Ids are generated by the app, but never trust a path piece blindly.
    final safe = recordId.replaceAll(RegExp(r'[^A-Za-z0-9._-]'), '_');
    return Directory('${base.path}/$folder/$safe');
  }

  Future<void> save(String recordId, CompositionVisuals visuals) async {
    if (visuals.isEmpty) return;
    final dir = await _dirFor(recordId);
    await dir.create(recursive: true);

    Future<void> outline(String name, SilhouetteMask? mask) async {
      if (mask == null) return;
      await File(
        '${dir.path}/$name',
      ).writeAsString(jsonEncode(encodeRunMask(mask)));
    }

    Future<void> photo(String name, Uint8List? bytes) async {
      if (bytes == null || bytes.isEmpty) return;
      await File('${dir.path}/$name').writeAsBytes(bytes, flush: true);
    }

    await outline('front_outline.json', visuals.frontOutline);
    await outline('side_outline.json', visuals.sideOutline);
    await photo('front_original.jpg', visuals.frontPhoto);
    await photo('side_original.jpg', visuals.sidePhoto);
  }

  /// What is stored for [recordId]; [CompositionVisuals.none] when nothing
  /// is, or a file cannot be read.
  Future<CompositionVisuals> load(String recordId) async {
    final dir = await _dirFor(recordId);
    if (!await dir.exists()) return CompositionVisuals.none;

    Future<SilhouetteMask?> outline(String name) async {
      final file = File('${dir.path}/$name');
      if (!await file.exists()) return null;
      try {
        final data = jsonDecode(await file.readAsString());
        if (data is! List) return null;
        return decodeRunMask(data.whereType<int>().toList());
      } catch (_) {
        return null;
      }
    }

    Future<Uint8List?> photo(String name) async {
      final file = File('${dir.path}/$name');
      if (!await file.exists()) return null;
      try {
        return await file.readAsBytes();
      } catch (_) {
        return null;
      }
    }

    return CompositionVisuals(
      frontOutline: await outline('front_outline.json'),
      sideOutline: await outline('side_outline.json'),
      frontPhoto: await photo('front_original.jpg'),
      sidePhoto: await photo('side_original.jpg'),
    );
  }

  /// Removes everything stored for [recordId].
  Future<void> delete(String recordId) async {
    final dir = await _dirFor(recordId);
    if (await dir.exists()) await dir.delete(recursive: true);
  }

  /// Removes only the photos for [recordId], keeping the outlines.
  Future<void> deletePhotos(String recordId) async {
    final dir = await _dirFor(recordId);
    for (final name in [
      'front.jpg',
      'side.jpg',
      'front_original.jpg',
      'side_original.jpg',
    ]) {
      final file = File('${dir.path}/$name');
      if (await file.exists()) await file.delete();
    }
  }
}
